import pandas as pd
import plotly.express as px

# Filter data for Selangor
df_selangor = df_final_merged[
    df_final_merged['state'] == 'Selangor'
].copy()

# Convert date column to datetime
df_selangor['date'] = pd.to_datetime(df_selangor['date'])

# Extract year
df_selangor['year'] = df_selangor['date'].dt.year.astype(str)

# Keep only 2022 and 2024
df_selangor = df_selangor[
    df_selangor['year'].isin(['2022', '2024'])
].copy()

# Sort constituencies by mean income in 2024
sort_order = (
    df_selangor[df_selangor['year'] == '2024']
    .sort_values(by='income_mean', ascending=False)
    ['parlimen']
    .tolist()
)

# Create interactive clustered horizontal bar chart
fig = px.bar(
    df_selangor,
    x='income_mean',
    y='parlimen',
    color='year',
    barmode='group',
    orientation='h',
    text='income_mean',
    category_orders={
        'parlimen': sort_order,
        'year': ['2022', '2024']
    },
    color_discrete_sequence=['#9ECAE1', '#2171B5'],
    title='Comparison of Mean Household Income Across Parliamentary Constituencies in Selangor (2022 vs 2024)',
    labels={
        'income_mean': 'Mean Household Income (RM)',
        'parlimen': 'Parliamentary Constituency',
        'year': 'Year'
    },
    hover_data={
        'income_mean': ':,.0f',
        'income_median': ':,.0f',
        'poverty_absolute': ':.2f'
    }
)

# Display income values on bars
fig.update_traces(
    texttemplate='RM %{x:,.0f}',
    textposition='outside',
    cliponaxis=False
)

# Customize chart layout
fig.update_layout(
    template='plotly_white',
    title_x=0.5,
    height=850,
    barmode='group',
    bargap=0.25,
    margin=dict(l=150, r=100, t=100, b=60),
    xaxis_title='Mean Household Income (RM)',
    yaxis_title='Parliamentary Constituency',
    legend_title='Year',
    hoverlabel=dict(
        bgcolor='white',
        font_size=12
    ),
    xaxis=dict(
        showgrid=True,
        gridcolor='lightgrey'
    )
)

# Display interactive chart
fig.show()